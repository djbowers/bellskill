#!/usr/bin/env node
// Movement catalog loader/validator (PROD-153).
//
// Reads the committed, self-authored Kettlebell + Bodyweight catalog at
// `scripts/data/movements.csv` (the source of truth), validates every row
// against the app's live vocabularies and the weight-mode reachability rules,
// and can emit the SQL `INSERT ... VALUES` block used by the slim-catalog
// migration.
//
// There is NO live-database write path. The catalog is loaded reproducibly by
// the migration (`supabase/migrations/*_slim_movements_catalog.sql`) on every
// `supabase db reset`, and auto-deploys to staging/prod via the supabase-*
// workflows. To change the catalog: edit `scripts/data/movements.csv`, run this
// validator, then regenerate the migration's VALUES block with `--emit-sql`.
//
// Usage:
//   node scripts/ingest-movements.mjs             validate (default); exits non-zero on any violation
//   node scripts/ingest-movements.mjs --emit-sql  print the INSERT ... VALUES block to stdout
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const CSV_PATH = resolve(HERE, 'data', 'movements.csv');

// The 7 authored columns, in order. `id` is generated by the table default.
export const COLUMNS = [
  'Movement',
  'Primary Equipment',
  '# Primary Items',
  'Single or Double Arm',
  'Target Muscle Group',
  'Difficulty Level',
  'Movement Pattern #1',
];

// --- App live vocabularies -------------------------------------------------
// These MUST stay in sync with the surviving `movements` columns and their
// consumers. Equipment is intentionally narrowed to the two classes the workout
// builder can ever surface (src/utils/movementWeightModeFilter.ts). Muscle
// groups / difficulty levels mirror the app's filterable vocabulary — the
// MuscleGroup / DifficultyLevel unions in src/types and the matching Explore
// filter constants in MovementsPage — so the CSV, validator, and Explore filters
// share one value set. Movement patterns are restricted to the values the
// pattern_debt_window CASE recognizes
// (supabase/migrations/20260624000000_create_pattern_debt_function.sql).
const EQUIPMENT = new Set(['Bodyweight', 'Kettlebell']);
const ARM = new Set(['Single Arm', 'Double Arm', 'No Arms']);
const PRIMARY_ITEMS = new Set([1, 2]);
const MUSCLE_GROUPS = new Set([
  'Abdominals',
  'Adductors',
  'Back',
  'Calves',
  'Chest',
  'Forearms',
  'Glutes',
  'Hamstrings',
  'Quadriceps',
  'Shoulders',
  'Trapezius',
  'Triceps',
]);
const DIFFICULTY_LEVELS = new Set(['Beginner', 'Intermediate', 'Expert']);
const MOVEMENT_PATTERNS = new Set([
  'Hip Hinge',
  'Hip Dominant',
  'Hip Extension',
  'Knee Dominant',
  'Vertical Push',
  'Horizontal Push',
  'Vertical Pull',
  'Horizontal Pull',
  'Loaded Carry',
  'Rotational',
  'Spinal Rotational',
]);

// Mirror of src/utils/movementWeightModeFilter.ts: every Kettlebell row must be
// reachable in exactly one builder weight mode.
//   2h     -> Kettlebell, 1 item, Double Arm
//   1h     -> Kettlebell, 1 item, Single Arm
//   double -> Kettlebell, 2 items, Double Arm
// A Kettlebell "2 items + Single Arm" combo matches no mode and is stranded.
const kettlebellReachable = (items, arm) =>
  (items === 1 && arm === 'Double Arm') ||
  (items === 1 && arm === 'Single Arm') ||
  (items === 2 && arm === 'Double Arm');

// --- Minimal RFC-4180 CSV parser ------------------------------------------
export const parseCsv = (text) => {
  const rows = [];
  let field = '';
  let record = [];
  let inQuotes = false;
  const pushField = () => {
    record.push(field);
    field = '';
  };
  const pushRecord = () => {
    pushField();
    rows.push(record);
    record = [];
  };
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ',') {
      pushField();
    } else if (c === '\r') {
      // ignore; handled by \n
    } else if (c === '\n') {
      pushRecord();
    } else {
      field += c;
    }
  }
  // Trailing field/record (file may not end with a newline).
  if (field !== '' || record.length > 0) pushRecord();
  return rows.filter((r) => r.length > 1 || (r.length === 1 && r[0] !== ''));
};

export const loadCatalog = () => {
  const text = readFileSync(CSV_PATH, 'utf8');
  const rows = parseCsv(text);
  if (rows.length === 0) throw new Error('movements.csv is empty');
  const header = rows[0];
  if (
    header.length !== COLUMNS.length ||
    header.some((h, i) => h !== COLUMNS[i])
  ) {
    throw new Error(
      `movements.csv header mismatch.\n  expected: ${COLUMNS.join(', ')}\n  got:      ${header.join(', ')}`,
    );
  }
  return rows.slice(1).map((r) => ({
    Movement: r[0],
    'Primary Equipment': r[1],
    '# Primary Items': r[2],
    'Single or Double Arm': r[3],
    'Target Muscle Group': r[4],
    'Difficulty Level': r[5],
    'Movement Pattern #1': r[6],
  }));
};

export const validate = (records) => {
  const errors = [];
  const seen = new Set();
  records.forEach((row, idx) => {
    const line = idx + 2; // account for header + 1-indexing
    const name = row.Movement;
    if (!name || !name.trim()) errors.push(`L${line}: empty Movement name`);
    const key = (name || '').toLowerCase();
    if (seen.has(key)) errors.push(`L${line}: duplicate Movement "${name}"`);
    seen.add(key);

    const equipment = row['Primary Equipment'];
    if (!EQUIPMENT.has(equipment))
      errors.push(
        `L${line} "${name}": invalid Primary Equipment "${equipment}"`,
      );

    const items = Number(row['# Primary Items']);
    if (!PRIMARY_ITEMS.has(items))
      errors.push(
        `L${line} "${name}": invalid # Primary Items "${row['# Primary Items']}"`,
      );

    const arm = row['Single or Double Arm'];
    if (!ARM.has(arm))
      errors.push(`L${line} "${name}": invalid Single or Double Arm "${arm}"`);

    if (!MUSCLE_GROUPS.has(row['Target Muscle Group']))
      errors.push(
        `L${line} "${name}": invalid Target Muscle Group "${row['Target Muscle Group']}"`,
      );

    if (!DIFFICULTY_LEVELS.has(row['Difficulty Level']))
      errors.push(
        `L${line} "${name}": invalid Difficulty Level "${row['Difficulty Level']}"`,
      );

    if (!MOVEMENT_PATTERNS.has(row['Movement Pattern #1']))
      errors.push(
        `L${line} "${name}": Movement Pattern #1 "${row['Movement Pattern #1']}" is not recognized by pattern_debt_window`,
      );

    // Kettlebell rows must be reachable in a builder weight mode.
    if (equipment === 'Kettlebell' && !kettlebellReachable(items, arm))
      errors.push(
        `L${line} "${name}": Kettlebell row is weight-mode unreachable (${items} item(s) + ${arm})`,
      );
  });
  return errors;
};

const sqlLiteral = (value) => `'${String(value).replace(/'/g, "''")}'`;

export const emitSql = (records) => {
  const cols = COLUMNS.map((c) => `"${c}"`).join(', ');
  const values = records
    .map((row) => {
      const cells = [
        sqlLiteral(row.Movement),
        sqlLiteral(row['Primary Equipment']),
        String(Number(row['# Primary Items'])),
        sqlLiteral(row['Single or Double Arm']),
        sqlLiteral(row['Target Muscle Group']),
        sqlLiteral(row['Difficulty Level']),
        sqlLiteral(row['Movement Pattern #1']),
      ];
      return `  (${cells.join(', ')})`;
    })
    .join(',\n');
  return `INSERT INTO public.movements (${cols}) VALUES\n${values};`;
};

const main = () => {
  const records = loadCatalog();
  const errors = validate(records);
  if (errors.length > 0) {
    console.error(`✗ ${errors.length} validation error(s) in ${CSV_PATH}:`);
    for (const e of errors) console.error(`  - ${e}`);
    process.exit(1);
  }

  if (process.argv.includes('--emit-sql')) {
    process.stdout.write(emitSql(records) + '\n');
    return;
  }

  const kb = records.filter(
    (r) => r['Primary Equipment'] === 'Kettlebell',
  ).length;
  const bw = records.filter(
    (r) => r['Primary Equipment'] === 'Bodyweight',
  ).length;
  console.log(
    `✓ ${records.length} movements valid (${kb} Kettlebell, ${bw} Bodyweight).`,
  );
};

// Only run when executed directly (not when imported for the SQL generator/tests).
if (
  process.argv[1] &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
) {
  main();
}
